"""Selectively normalize generated round-8 map art to the requested world grid.

No character, existing PNG, scene or runtime code is modified. Source art is
generated by built-in imagegen; this script controls geometry, palette and joins.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SIZES = {'hub-top':(352,256), 'hub-repeat':(352,288), 'hub-bottom':(352,320), 'guestbook-bg':(352,448)}
G = (144,173,89); N = (239,219,177)


def inverse(value, source, target):
    for i in range(len(target)-1):
        if value <= target[i+1]:
            return source[i]+(value-target[i])*(source[i+1]-source[i])/(target[i+1]-target[i])
    return source[-1]-1


def rows(im, source, target):
    result=Image.new('RGB',im.size)
    for a,b,c,d in zip(source,source[1:],target,target[1:]):
        result.paste(im.crop((0,a,352,b)).resize((352,d-c),Image.Resampling.BOX),(0,c))
    return result


def columns(im, source, target):
    result=Image.new('RGB',im.size)
    for a,b,c,d in zip(source,source[1:],target,target[1:]):
        result.paste(im.crop((a,0,b,im.height)).resize((d-c,im.height),Image.Resampling.BOX),(c,0))
    return result


def top_geometry(im):
    # Source surface/steps were too high; put the generated painted surfaces
    # on the requested y128..164 and y164..184, without redrawing them.
    im=rows(im,[0,6,112,136,154,256],[0,8,128,164,184,256])
    profiles=[([0,108,120,232,244,352],[0,88,101,251,264,352]),
              ([0,59,110,242,293,352],[0,45,101,251,307,352]),
              ([0,90,135,218,263,352],[0,88,128,224,264,352])]
    result=Image.new('RGB',im.size)
    for y in range(256):
        if y<112: a=b=0; t=0
        elif y<128: a,b,t=0,1,(y-112)/16
        elif y<176: a=b=1; t=0
        elif y<192: a,b,t=1,2,(y-176)/16
        else: a=b=2; t=0
        for x in range(352):
            sx=(1-t)*inverse(x,*profiles[a])+t*inverse(x,*profiles[b])
            result.putpixel((x,y),im.getpixel((max(0,min(351,round(sx))),y)))
    return result


def normalize_color(name,im):
    for y in range(im.height):
        for x in range(352):
            r,g,b=im.getpixel((x,y))
            # Preserve crowns, flowers, deep foliage and grass tuft silhouettes.
            crown = name=='hub-top' and y<96 and (x<90 or x>262)
            if not crown and 105<r<190 and 140<g<210 and 40<b<130 and 5<g-r<55:
                delta=max(-6,min(6,round((g-174)/5)*2))
                im.putpixel((x,y),tuple(max(0,min(255,v+delta)) for v in G))
            path = (name=='hub-repeat' and 128<=x<224) or (name=='hub-top' and y>=184 and 128<=x<224) or (name=='hub-bottom' and ((y<32 and 128<=x<224) or (32<=y<288 and 32<=x<320))) or (name=='guestbook-bg' and y>=160 and 160<=x<192)
            if path and r>175 and r>=g and g>b+10:
                delta=max(-8,min(8,round((g-218)/4)))
                im.putpixel((x,y),tuple(max(0,min(255,v+delta)) for v in N))
    return im


def plain_sand(rgb):
    r,g,b=rgb[:3]
    return r>205 and g>175 and r>=g and g>b+12


def main():
    provenance=json.loads((ROOT/'assets/round8-prompts.json').read_text(encoding='utf-8'))
    for path,digest in provenance['previous_png_sha256'].items():
        assert hashlib.sha256((ROOT/path).read_bytes()).hexdigest()==digest, path
    output={}
    for name,size in SIZES.items():
        im=Image.open(ROOT/'raw/round8-source'/f'{name}.png').convert('RGB').resize(size,Image.Resampling.BOX)
        if name=='hub-top': im=top_geometry(im)
        elif name=='hub-repeat': im=columns(im,[0,86,137,215,266,352],[0,88,128,224,264,352])
        elif name=='hub-bottom':
            im=rows(im,[0,65,104,288,320],[0,32,64,288,320])
            upper=columns(im,[0,90,142,210,262,352],[0,88,128,224,264,352])
            lower=columns(im,[0,30,322,352],[0,32,320,352])
            for y in range(320):
                im.paste((upper if y<32 else lower).crop((0,y,352,y+1)),(0,y))
        elif name=='guestbook-bg':
            im=rows(im,[0,208,448],[0,160,448])
            low=columns(im,[0,134,156,196,218,352],[0,144,160,192,208,352])
            im.paste(low.crop((0,160,352,448)),(0,160))
        output[name]=normalize_color(name,im)
    repeat=output['hub-repeat']
    # Exact same terminal pixels and a short mirrored foliage transition give
    # a cyclic painted band; the body remains one non-tiled generated scene.
    repeat.paste(repeat.crop((0,0,352,8)).transpose(Image.Transpose.FLIP_TOP_BOTTOM),(0,280))
    output['hub-top'].paste(repeat.crop((0,272,352,288)),(0,240))
    output['hub-bottom'].paste(repeat.crop((0,0,352,16)),(0,0))
    bottom=output['hub-bottom']
    # Clear painted edge intrusions from code-owned door/sign/cake space.
    for y in range(64,288):
        for x in range(32,320):
            if not plain_sand(bottom.getpixel((x,y))):
                sample=bottom.getpixel((160+(x+y)%24,160+(y%32)))
                bottom.putpixel((x,y),sample if plain_sand(sample) else N)
    for y in range(288,320):
        factor=1-(y-287)/320
        for x in range(352): bottom.putpixel((x,y),tuple(round(v*factor) for v in bottom.getpixel((x,y))))
    # One common 64-entry palette prevents color drift at the three seams.
    stack=Image.new('RGB',(352,sum(im.height for im in output.values())))
    yy=0
    for im in output.values(): stack.paste(im,(0,yy)); yy+=im.height
    quant=stack.quantize(colors=62,dither=Image.Dither.NONE)
    palette=Image.new('P',(1,1)); palette.putpalette(list(G)+list(N)+quant.getpalette()[:186]+list(G)*192)
    output={name:im.quantize(palette=palette,dither=Image.Dither.NONE).convert('RGBA') for name,im in output.items()}
    report={}
    maps=ROOT/'assets/maps'; maps.mkdir(parents=True,exist_ok=True)
    for name,im in output.items():
        assert im.size==SIZES[name] and im.getchannel('A').getextrema()==(255,255)
        assert len(im.getcolors(im.width*im.height))<=64
        im.save(maps/f'{name}.png')
        report[name]={'file':f'{name}.png','size':list(im.size),'bbox':im.getbbox(),'colors':len(im.getcolors(im.width*im.height)),'alpha_values':[255]}
    def first(im): return im.crop((0,0,352,1)).tobytes()
    def last(im): return im.crop((0,im.height-1,352,im.height)).tobytes()
    assert last(output['hub-top'])==first(output['hub-repeat'])==last(output['hub-repeat'])==first(output['hub-bottom'])
    report['joins']={'top_repeat':True,'repeat_repeat':True,'repeat_bottom':True,'shared_row_sha256':hashlib.sha256(first(output['hub-repeat'])).hexdigest()}
    doors=[(32,64,64,96),(288,64,320,96),(32,192,64,224),(288,192,320,224)]
    for rect in doors:
        assert all(plain_sand(p) for p in output['hub-bottom'].crop(rect).get_flattened_data()), rect
    report['geometry']={'aisle':[128,224],'flower_bands':[[88,128],[224,264]],'stage_top':[101,128,251,164],'steps':[101,164,251,184],'planters':[[45,140,101,184],[251,140,307,184]],'bottom_global_y':544,'door_local_rects':doors,'guestbook_mailbox':[128,64,192,160],'guestbook_path':[160,160,192,448]}
    manifest_path=ROOT/'assets/manifest.json'
    manifest=json.loads(manifest_path.read_text(encoding='utf-8'))
    for name in SIZES:
        if name not in manifest['maps']: manifest['maps'].append(name)
        manifest.setdefault('files',{}).setdefault('maps',{})[name]=f'{name}.png'
    manifest_path.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (ROOT/'assets/round8-report.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
    merged=Image.new('RGBA',(352,864)); yy=0
    for name in ['hub-top','hub-repeat','hub-bottom']:
        im=output[name]; merged.paste(im,(0,yy)); yy+=im.height
    merged.save(ROOT/'assets/round8-hub-preview.png')
    grid=merged.copy(); d=ImageDraw.Draw(grid)
    for x in range(0,353,32): d.line((x,0,x,864),fill=(35,40,30,80))
    for y in range(0,865,32): d.line((0,y,352,y),fill=(35,40,30,80))
    for y in [256,544]: d.line((0,y,352,y),fill='#d36164',width=2)
    grid.save(ROOT/'assets/round8-hub-grid.png')
    print(json.dumps(report,indent=2))


if __name__=='__main__': main()
